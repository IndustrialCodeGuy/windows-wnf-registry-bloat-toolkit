        [pscustomobject]@{
            LogName       = "$StandardLog (filtered)"
            Exists        = $true
            Enabled       = $true
            RecordCount   = $null
            ExportedCount = $Rows.Count
            CsvPath       = $CsvPath
            Error         = ''
        }
    )

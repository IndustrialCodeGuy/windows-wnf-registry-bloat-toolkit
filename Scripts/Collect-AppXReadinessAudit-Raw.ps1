                Length        = $_.Length
                CreationTime  = $_.CreationTime
                LastWriteTime = $_.LastWriteTime
                UserSid       = $Sid
            }
        }
    )
}

$ResiliencyRows |
    Export-Csv -LiteralPath (
        Join-Path $OutputDirectory 'AppRepository-ResiliencyFiles.csv'
    ) -NoTypeInformation -Encoding UTF8

$ResiliencyRows |
